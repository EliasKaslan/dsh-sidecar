#!/usr/bin/env node
/**
 * Build both halves of the plugin.
 *
 * The host half is ordinary ESM: every `@deepseek-ai/*` request stays external
 * and resolves through the harness installation at run time.
 *
 * The client half must be a pre-built, self-registering CommonJS factory:
 * the harness streams `lib/client.js` into the page unchanged and the browser
 * module loader hands the factory a `require` that only resolves the platform
 * seed table. React, the JSX runtime and the shared UI primitives therefore
 * stay external; everything else is bundled in.
 */
import { build } from 'esbuild'
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))

const PLATFORM_EXTERNALS = [
  'react',
  'react-dom',
  'react/jsx-runtime',
  '@deepseek-ai/cordis',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-dockkit',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-slots',
]

const banner = `/* ${pkg.name} v${pkg.version} — MIT — generated by scripts/build.mjs; do not edit. */`

async function buildHost() {
  await build({
    entryPoints: [join(root, 'src/host/index.ts')],
    outfile: join(root, 'lib/index.js'),
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    external: ['@deepseek-ai/*', 'node:*'],
    keepNames: true,
    legalComments: 'none',
    banner: { js: banner },
    logLevel: 'warning',
  })
}

function wrappedClient(code) {
  return `/* ${pkg.name} v${pkg.version} — MIT — generated by scripts/build.mjs; do not edit. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${code}
    return module.exports;
  }
});
`
}

async function buildClient() {
  const outfile = join(root, '.tmp/client.cjs')
  await build({
    entryPoints: [join(root, 'src/client/index.tsx')],
    outfile,
    bundle: true,
    platform: 'browser',
    format: 'cjs',
    target: 'es2022',
    jsx: 'automatic',
    external: PLATFORM_EXTERNALS,
    keepNames: true,
    legalComments: 'none',
    logLevel: 'warning',
  })
  const code = await readFile(outfile, 'utf8')
  const imports = [...code.matchAll(/\brequire\("([^"]+)"\)/g)].map((match) => match[1])
  const unexpected = [...new Set(imports)].filter((spec) => !PLATFORM_EXTERNALS.includes(spec))
  if (unexpected.length > 0) {
    throw new Error(`client bundle requested non-platform modules: ${unexpected.join(', ')}`)
  }
  await writeFile(join(root, 'lib/client.js'), wrappedClient(code), 'utf8')
}

await rm(join(root, 'lib'), { recursive: true, force: true })
await rm(join(root, '.tmp'), { recursive: true, force: true })
await mkdir(join(root, 'lib'), { recursive: true })
await mkdir(join(root, '.tmp'), { recursive: true })

await buildHost()
await buildClient()

const host = await readFile(join(root, 'lib/index.js'), 'utf8')
const client = await readFile(join(root, 'lib/client.js'), 'utf8')
if (!host.includes('export')) throw new Error('host bundle has no exports')
if (!client.startsWith(`/* ${pkg.name}`) || !client.includes('window.__ModuleLoader__.load')) {
  throw new Error('client bundle is not a ModuleLoader factory')
}
console.log(`built ${pkg.name}: lib/index.js ${host.length}B, lib/client.js ${client.length}B`)
